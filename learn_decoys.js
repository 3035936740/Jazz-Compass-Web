/** 给一道题补上第 4 个选项 / 第 4 对 */
export function withDecoys(card) {
  if (card?.type === 'choice' && card.options?.length === 3) {
    const extra = EXTRA_OPTIONS[decoyKey(card)];
    return extra === undefined ? card : { ...card, options: [...card.options, extra] };
  }
  if (card?.type === 'match' && card.pairs?.length < 4) {
    const extra = EXTRA_PAIRS[decoyKey(card)];
    return extra ? { ...card, pairs: [...card.pairs, ...extra.pairs], ...(extra.prompt ? { prompt: extra.prompt } : {}) } : card;
  }
  return card;
}
