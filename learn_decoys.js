/** 题目的内容键：选择题看题干 + 选项，连线题看题干 + 配对（只取中文） */
export function decoyKey(card) {
  const zh = (v) => (typeof v === 'string' ? v : v?.zh ?? '');
  const core = card.type === 'match' ? `${zh(card.prompt)}|${card.pairs.map(([a, b]) => `${zh(a)}=${zh(b)}`).join('|')}` : `${zh(card.prompt)}|${card.options.map(zh).join('|')}`;
  let h = 5381; for (let i = 0; i < core.length; i += 1) h = ((h * 33) ^ core.charCodeAt(i)) >>> 0;
  return `d${h.toString(36)}`;
}

